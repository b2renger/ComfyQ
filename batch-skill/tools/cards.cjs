#!/usr/bin/env node
/**
 * Write batch-skill/reference/cards.md: every card a batch can use, with its
 * title, the model it runs, what it does, and the columns a batch table gives it.
 *
 * Read from the same place the Batches tab reads (describeCards, behind
 * GET /storyboard/cards) plus each card's summary and description, so the skill
 * names the columns the planner accepts, not a copy that drifts from them.
 *
 *   node batch-skill/tools/cards.cjs           write the file
 *   node batch-skill/tools/cards.cjs --check   exit 1 if the file is out of date
 *
 * Timings are left out on purpose: every calibration moves them, and the
 * preview prints a batch's own estimate.
 */
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');
const OUT = path.join(REPO, 'batch-skill', 'reference', 'cards.md');

const args = process.argv.slice(2);
const unknown = args.filter(a => a !== '--check');
if (unknown.length) {
    console.error(`Unknown option ${unknown.join(', ')}. Usage: node batch-skill/tools/cards.cjs [--check]`);
    process.exit(1);
}
const CHECK = args.includes('--check');

const { WorkflowRegistry } = require(path.join(REPO, 'server', 'workflows', 'workflowRegistry'));
const { describeCards } = require(path.join(REPO, 'server', 'batch', 'batchPlan'));

const CATEGORY = {
    't2i': 'Pictures from words',
    'image-edit': 'Editing a picture',
    'i2i': 'Picture to picture (enlarging, restoring)',
    'preprocessor': 'Preparing a picture (depth, edges, masks)',
    'i2v': 'Making a video',
    'video-edit': 'Editing a video',
    'audio': 'Sound and music',
    '3d': '3D',
    'description': 'Describing a picture or a video in words',
};

const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const cut = (s, n) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

function settingLine(s) {
    let v = '';
    if (Array.isArray(s.options) && s.options.length) {
        const shown = s.options.slice(0, 8).map(o => one(o)).join(', ');
        v = ` — one of: ${shown}${s.options.length > 8 ? `, … (${s.options.length})` : ''}`;
    } else if (s.min != null || s.max != null) {
        v = ` — ${s.min ?? ''}…${s.max ?? ''}${s.step != null ? `, step ${s.step}` : ''}`;
    } else if (s.type === 'checkbox' || s.type === 'boolean') {
        v = ' — yes / no';
    }
    const def = s.default === null || s.default === undefined || s.default === '' ? '' : `; default ${cut(one(s.default), 60)}`;
    return `  - \`${s.key}\` ${cut(one(s.label), 110)}${v}${def}`;
}

function cardBlock(card, about) {
    const out = [];
    out.push(`### \`${card.id}\``);
    out.push('');
    const tags = [`makes **${card.produces || 'unknown'}**`];
    if (card.experimental) tags.push('experimental');
    out.push(`**${one(card.title)}** · model: **${one(card.name) || '—'}** · ${tags.join(' · ')}`);
    out.push('');
    if (about.summary) { out.push(one(about.summary)); out.push(''); }
    if (about.description) { out.push(`> ${one(about.description)}`); out.push(''); }
    const guides = (about.promptGuides || []).filter(g => g && g.url);
    if (guides.length) {
        out.push(`Prompting: ${guides.map(g => `[${one(g.label) || 'guide'}](${g.url})`).join(' · ')}`);
        if (guides[0].tip) out.push(`Tip: ${one(guides[0].tip)}`);
        out.push('');
    }
    const cols = [];
    if (card.prompt) cols.push(`\`prompt\` (${one(card.prompt.label)})`);
    if (card.negative) cols.push(`\`negative\` (${one(card.negative.label)})`);
    if (card.seed) cols.push('`seed`');
    for (const i of card.inputs) cols.push(`\`${i.column}\` ${one(i.label)} (${i.kind}, ${i.required ? 'required' : 'optional'})`);
    out.push(`Columns: ${cols.length ? cols.join(' · ') : 'none besides `workflow`'}`);
    if (card.settings.length) {
        out.push('');
        out.push('Settings (a column named by the key; empty keeps the default):');
        for (const s of card.settings) out.push(settingLine(s));
    }
    out.push('');
    return out.join('\n');
}

function build() {
    const registry = new WorkflowRegistry(path.join(REPO, 'workflows'));
    registry.discover();
    const cards = describeCards(registry);
    const about = new Map(registry.summaries({ includeUnavailable: false, includeHidden: false })
        .filter(s => s && !s.unavailable).map(s => [s.id, s]));
    const lines = [];
    lines.push('# The cards');
    lines.push('');
    lines.push('<!-- Generated by `node batch-skill/tools/cards.cjs` from `workflows/*/*.meta.json`. Do not edit:');
    lines.push('     change the card in the admin metadata editor, then run the script again. -->');
    lines.push('');
    lines.push(`${cards.length} cards, every one a batch table can name in its \`workflow\` column. For each: its id (what`);
    lines.push('goes in the cell), the title students see, the model it runs, what it does in plain words, the');
    lines.push('technical description, and the columns a row gives it. The `id`, `workflow`, `repeat` and `notes`');
    lines.push('columns work on every card. Inputs take a row id, `file:`, `folder:`, `job:` or `empty`: see');
    lines.push('[../SKILL.md](../SKILL.md) and [docs/batch-format.md](../../docs/batch-format.md).');
    lines.push('');
    lines.push('A storyboard (.md) uses only the six cards named in [workflows.md](workflows.md).');
    lines.push('');
    let cat = null;
    for (const card of cards) {
        if (card.category !== cat) {
            cat = card.category;
            const n = cards.filter(c => c.category === cat).length;
            lines.push(`## ${CATEGORY[cat] || cat} (\`${cat}\`, ${n})`);
            lines.push('');
        }
        lines.push(cardBlock(card, about.get(card.id) || {}));
    }
    return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

const text = build();
if (CHECK) {
    let current = null;
    try { current = fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    if (current !== text) {
        console.error(`batch-skill/reference/cards.md is out of date with the cards (${current === null ? 'missing' : 'differs'}).`);
        console.error('Run: node batch-skill/tools/cards.cjs');
        process.exit(1);
    }
    console.log('batch-skill/reference/cards.md matches the cards.');
} else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(REPO, OUT)}: ${text.split('\n### ').length - 1} cards, ${Math.round(text.length / 1024)} KB`);
}
